# Downloads the mockup's three typefaces (Manrope, Sora, IBM Plex Mono) from Google Fonts
# into src/GlassMixer.App/ui/fonts, with their licences, so the app works offline.
#   powershell -ExecutionPolicy Bypass -File tools/get-fonts.ps1
$dest = Join-Path $PSScriptRoot "..\src\GlassMixer.App\ui\fonts"
New-Item -ItemType Directory -Force $dest | Out-Null

# Google sends the modern .woff2 format only to browsers it recognises.
$ua = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"
$api = "https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@500&family=Manrope:wght@400..700&family=Sora:wght@600&display=swap"
$css = (Invoke-WebRequest -UseBasicParsing -UserAgent $ua $api).Content

# Keep the Latin and Latin Extended blocks; each points at one .woff2 file.
# Each block is copied into fonts.css with its web address swapped for the local file.
$fontsCss = @("/* Generated by tools/get-fonts.ps1 from Google Fonts. Licences: OFL-*.txt in this folder. */")
$blocks = [regex]::Matches($css, '/\* (latin|latin-ext) \*/\s*@font-face \{(.*?)\}', 'Singleline')
foreach ($b in $blocks) {
    $subset = $b.Groups[1].Value
    $body = $b.Groups[2].Value
    $family = [regex]::Match($body, "font-family: '([^']+)'").Groups[1].Value
    $url = [regex]::Match($body, 'url\((https://[^)]+\.woff2)\)').Groups[1].Value
    $file = (($family -replace ' ', '') + "-$subset.woff2").ToLower()
    Invoke-WebRequest -UseBasicParsing -UserAgent $ua $url -OutFile (Join-Path $dest $file)
    $fontsCss += "/* $subset */`n@font-face {" + $body.Replace($url, $file) + "}"
    "$file  <-  $url"
}
Set-Content -Path (Join-Path $dest "fonts.css") -Value ($fontsCss -join "`n") -Encoding UTF8

# The SIL Open Font License lets us ship these fonts, as long as the licence goes with them.
foreach ($f in @(@('manrope', 'Manrope'), @('sora', 'Sora'), @('ibmplexmono', 'IBMPlexMono'))) {
    Invoke-WebRequest -UseBasicParsing "https://raw.githubusercontent.com/google/fonts/main/ofl/$($f[0])/OFL.txt" -OutFile (Join-Path $dest "OFL-$($f[1]).txt")
    "OFL-$($f[1]).txt"
}
